window.DementiaApp.i18n = {
  locale: 'en',
  translations: translations,
  setLocale: function(lang) {
    this.locale = lang;
    this.translateDOM();
    if (window.App && window.App.reRender) {
      window.App.reRender();
    }
  },
  t: function(text) {
    if (this.locale === 'en' || !this.translations[this.locale]) return text;
    return this.translations[this.locale][text] || text;
  },
  translateDOM: function() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      el.textContent = this.t(key);
    });
    // Update progress label specifically
    const progressLabel = document.getElementById('progressLabel');
    if (progressLabel && window.App) {
      window.App.updateProgress();
    }
    
    // Disclaimer is set in JS initialization
    const disclaimerEl = document.getElementById('disclaimerText');
    if (disclaimerEl && window.DementiaApp.DISCLAIMER) {
      disclaimerEl.textContent = this.t(window.DementiaApp.DISCLAIMER);
    }
  }
};

// Global shorthand
window.t = function(text) {
  return window.DementiaApp.i18n.t(text);
};

// Run initial translation on load
document.addEventListener('DOMContentLoaded', () => {
  window.DementiaApp.i18n.translateDOM();
});
